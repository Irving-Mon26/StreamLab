 stream=spawn(env.FFMPEG_PATH,[...videoArgs,`rtmp://127.0.0.1:1936/live/${changed.obs_key}`],{stdio:'ignore'});
 await until(async()=> (await api('/api/channels/prueba_uno')).data.is_live);
