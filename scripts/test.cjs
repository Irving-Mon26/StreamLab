 execFileSync(env.FFMPEG_PATH,['-v','error','-i',base+'/media/live/prueba_uno/index.m3u8','-t','2','-f','null','-'],{timeout:15000,stdio:'pipe'});
 await until(async()=> !(await api('/api/channels/prueba_uno')).data.is_live,20000);
